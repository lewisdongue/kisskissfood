import path from "path";
import { readFileSync, writeFileSync, existsSync } from "fs";
import { loadEnv, type Plugin } from "vite";
import { defineConfig } from "@lovable.dev/vite-tanstack-config";
import { nodePolyfills } from "vite-plugin-node-polyfills";

const SW_FILENAME = "firebase-messaging-sw.js";

function firebaseSwInjector(env: Record<string, string>): Plugin {
  const swTemplatePath = path.resolve(__dirname, "public", `${SW_FILENAME}.template`);
  const swPublicPath = path.resolve(__dirname, "public", SW_FILENAME);

  const replacements: Record<string, string> = {
    __FIREBASE_API_KEY__: env.VITE_FIREBASE_API_KEY || "",
    __FIREBASE_AUTH_DOMAIN__: env.VITE_FIREBASE_AUTH_DOMAIN || "",
    __FIREBASE_PROJECT_ID__: env.VITE_FIREBASE_PROJECT_ID || "",
    __FIREBASE_STORAGE_BUCKET__: env.VITE_FIREBASE_STORAGE_BUCKET || "",
    __FIREBASE_MESSAGING_SENDER_ID__: env.VITE_FIREBASE_MESSAGING_SENDER_ID || "",
    __FIREBASE_APP_ID__: env.VITE_FIREBASE_APP_ID || "",
  };

  function injectSwConfig(targetPath: string) {
    const sourcePath = existsSync(swTemplatePath) ? swTemplatePath : targetPath;
    let contents = readFileSync(sourcePath, "utf-8");
    for (const [token, val] of Object.entries(replacements)) {
      contents = contents.replaceAll(token, val);
    }
    writeFileSync(targetPath, contents, "utf-8");
  }

  return {
    name: "inject-firebase-sw-config",
    enforce: "post",

    configureServer(server) {
      try {
        if (!existsSync(swTemplatePath)) {
          const raw = readFileSync(swPublicPath, "utf-8");
          if (raw.includes("__FIREBASE_API_KEY__")) {
            writeFileSync(swTemplatePath, raw, "utf-8");
          }
        }
        injectSwConfig(swPublicPath);
        server.config.logger.info("Injected Firebase config into public/firebase-messaging-sw.js (dev)");
      } catch (err) {
        server.config.logger.error("Failed to inject firebase sw config (dev): " + err);
      }
    },

    closeBundle() {
      try {
        const distSwPath = path.resolve(__dirname, "dist", SW_FILENAME);
        if (existsSync(distSwPath)) {
          injectSwConfig(distSwPath);
        } else {
          injectSwConfig(swPublicPath);
        }
      } catch (err) {
        throw new Error("Failed to inject firebase sw config: " + err);
      }
    },
  };
}

